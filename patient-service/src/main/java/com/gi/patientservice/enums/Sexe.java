package com.gi.patientservice.enums;

/**
 * Énumération représentant le sexe/genre d'un patient.
 * 
 * <p>Conforme aux standards médicaux internationaux et inclut une option
 * inclusive pour les patients ne s'identifiant pas dans la binarité de genre.
 * 
 * @author CabinetX Development Team
 * @version 1.0
 * @since 2024-01
 */
public enum Sexe {
    /** Sexe masculin */
    MASCULIN,
    
    /** Sexe féminin */
    FEMININ,
    
    /** Autre identité de genre ou non spécifié */
    AUTRE
}
